import pandas as pd

# ----------------------------------------------------------
# Load Dataset
# ----------------------------------------------------------

df = pd.read_csv("titanic.csv")

# ----------------------------------------------------------
# Q1. Display first 5 rows.
# ----------------------------------------------------------

print(df.head())

# ----------------------------------------------------------
# Q2. Display last 5 rows.
# ----------------------------------------------------------

print(df.tail())

# ----------------------------------------------------------
# Q3. Display dataset information.
# ----------------------------------------------------------

print(df.info())

# ----------------------------------------------------------
# Q4. Display statistical summary.
# ----------------------------------------------------------

print(df.describe())

# ----------------------------------------------------------
# Q5. Find shape of dataset.
# ----------------------------------------------------------

print(df.shape)

# ----------------------------------------------------------
# Q6. Display column names.
# ----------------------------------------------------------

print(df.columns)

# ----------------------------------------------------------
# Q7. Check missing values.
# ----------------------------------------------------------

print(df.isnull().sum())

# ----------------------------------------------------------
# Q8. Fill missing Age with median.
# ----------------------------------------------------------

df["Age"] = df["Age"].fillna(df["Age"].median())

# ----------------------------------------------------------
# Q9. Fill missing Embarked with mode.
# ----------------------------------------------------------

df["Embarked"] = df["Embarked"].fillna(df["Embarked"].mode()[0])

# ----------------------------------------------------------
# Q10. Remove duplicate rows.
# ----------------------------------------------------------

df = df.drop_duplicates()

# ----------------------------------------------------------
# Q11. Find average age.
# ----------------------------------------------------------

print(df["Age"].mean())

# ----------------------------------------------------------
# Q12. Find survival count.
# ----------------------------------------------------------

print(df["Survived"].value_counts())

# ----------------------------------------------------------
# Q13. Find average fare.
# ----------------------------------------------------------

print(df["Fare"].mean())

# ----------------------------------------------------------
# Q14. Find passengers by gender.
# ----------------------------------------------------------

print(df["Sex"].value_counts())

# ----------------------------------------------------------
# Q15. Find passengers older than 60.
# ----------------------------------------------------------

print(df[df["Age"] > 60])

# ----------------------------------------------------------
# Q16. Find passengers in First Class.
# ----------------------------------------------------------

print(df[df["Pclass"] == 1])

# ----------------------------------------------------------
# Q17. Sort passengers by Fare.
# ----------------------------------------------------------

print(df.sort_values(by="Fare", ascending=False))

# ----------------------------------------------------------
# Q18. Group by Sex and calculate average age.
# ----------------------------------------------------------

print(df.groupby("Sex")["Age"].mean())

# ----------------------------------------------------------
# Q19. Group by Passenger Class.
# ----------------------------------------------------------

print(df.groupby("Pclass")["Fare"].mean())

# ----------------------------------------------------------
# Q20. Save cleaned dataset.
# ----------------------------------------------------------

df.to_csv("cleaned_titanic.csv", index=False)

print("Cleaned dataset saved successfully!")

